const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const p = await (await b.newContext({viewport:{width:1366,height:900}, reducedMotion:'reduce'})).newPage()
  await p.goto('http://127.0.0.1:8082/', {waitUntil:'domcontentloaded', timeout:20000})
  await p.waitForTimeout(1200)
  const rail = await p.locator('.weekrail').boundingBox()
  await p.evaluate(y=>window.scrollTo(0,y-140), rail.y); await p.waitForTimeout(300)
  const g = await p.evaluate(()=>{const ps=[...document.querySelectorAll('.polaroid')].map(e=>e.getBoundingClientRect())
    const l=document.querySelector('.weekline-hit').getBoundingClientRect()
    return {x:(ps[0].right+ps[1].left)/2, y:l.top+l.height*0.35}})
  await p.mouse.move(g.x,g.y); await p.waitForTimeout(150)
  console.log(await p.evaluate(()=>`line anims ${document.querySelector('.weekline-ink').getAnimations().length}`
    +`, swinging ${[...document.querySelectorAll('.polaroid')].filter(e=>e.getAnimations().some(a=>a.animationName==='hangSwing')).length}`))
  await b.close()
})()
